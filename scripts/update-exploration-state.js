#!/usr/bin/env node
/**
 * update-exploration-state.js — regenerate qa/knowledgebase/exploration-state.md
 *
 * Live, human-readable Phase 1 dashboard. Replaces "open the screenshot grid"
 * with "cat the md file" — same gut-check, deterministic, no token cost.
 *
 * Inputs (any may be missing — script degrades gracefully):
 *   qa/crawl-state.json          (BFS strategy state — visited/queue)
 *   qa/trace-state.json          (targeted-trace state — current step)
 *   qa/sitemap-groups.json       (sitemap-spot-check — group progress)
 *   qa/knowledgebase/aria-snapshots/*.snapshot.json
 *   qa/decisions.md              (most recent decision)
 *   qa/platform-fingerprint.md   (strategy + fallback)
 *
 * Output:
 *   qa/knowledgebase/exploration-state.md   (overwritten)
 *
 * Call after EVERY page in BFS, after every trace step, or any time the agent
 * wants the user to be able to glance at progress.
 *
 * Usage:
 *   node scripts/update-exploration-state.js
 *   node scripts/update-exploration-state.js --current-url https://app.example.com/dashboard
 *   node scripts/update-exploration-state.js --note "Stalled on login form, switching to login-engage"
 */

const fs = require('fs');
const path = require('path');

const arg = (flag) => {
  const i = process.argv.indexOf(flag);
  return i !== -1 ? process.argv[i + 1] : null;
};

const CURRENT_URL = arg('--current-url');
const NOTE        = arg('--note');

const SNAP_DIR    = 'qa/knowledgebase/aria-snapshots';
const OUT         = 'qa/knowledgebase/exploration-state.md';

const readJson = (p) => fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : null;
const readText = (p) => fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';

// ── Inputs ────────────────────────────────────────────────────────────────
const crawl   = readJson('qa/crawl-state.json');
const trace   = readJson('qa/trace-state.json');
const sitemap = readJson('qa/sitemap-groups.json');

const snapshots = fs.existsSync(SNAP_DIR)
  ? fs.readdirSync(SNAP_DIR).filter(f => f.endsWith('.snapshot.json'))
  : [];

// Most recent decisions.md entry (last `## ` block)
const decisionsText = readText('qa/decisions.md');
const lastDecision = (() => {
  const blocks = decisionsText.split(/\n## /).slice(1);
  return blocks.length ? '## ' + blocks[blocks.length - 1].trim() : null;
})();

// Fingerprint strategy line
const fingerprintText = readText('qa/platform-fingerprint.md');
const strategyLine = (fingerprintText.match(/Strategy[:\s]+([^\n]+)/i) || [])[1] || 'unknown';
const fallbackLine = (fingerprintText.match(/Fallback[:\s]+([^\n]+)/i) || [])[1] || 'unknown';

// ── Derive table rows from per-snapshot JSON ──────────────────────────────
function summariseSnap(file) {
  try {
    const s = JSON.parse(fs.readFileSync(path.join(SNAP_DIR, file), 'utf8'));
    const d = s.dom || {};
    const els = (d.buttons?.length || 0) + (d.links?.length || 0) + (d.inputs?.length || 0);
    const h1  = (d.headings || []).find(h => h.level === 'H1')?.text?.split('\n')[0]?.slice(0, 50) || '—';
    const status =
      els === 0 ? '⚠ blank' :
      d.alerts?.length ? '⚠ alerts' :
      s.aria === null ? '⚠ no-aria' :
      '✅';
    return { file, url: d.url || '?', h1, els, status, capturedAt: s.capturedAt || null };
  } catch (_e) {
    return { file, url: '(parse error)', h1: '—', els: 0, status: '❌', capturedAt: null };
  }
}

const visitedRows = snapshots
  .map(summariseSnap)
  .sort((a, b) => (a.capturedAt || '').localeCompare(b.capturedAt || '') || a.file.localeCompare(b.file));

// ── Active strategy state ─────────────────────────────────────────────────
let queueRows = [];
let activeStrategy = 'bfs';
let queueLabel = 'Queue';

if (crawl) {
  activeStrategy = 'bfs';
  queueRows = (crawl.queue || []).slice(0, 20).map(item => ({
    url: typeof item === 'string' ? item : (item.url || JSON.stringify(item)),
    depth: typeof item === 'object' ? (item.depth ?? '') : '',
  }));
} else if (trace) {
  activeStrategy = 'targeted-trace';
  queueLabel = 'Remaining steps';
  queueRows = (trace.steps || []).filter(s => s.status === 'pending').slice(0, 20)
    .map(s => ({ url: s.target || s.action || JSON.stringify(s), depth: s.step || '' }));
} else if (sitemap) {
  activeStrategy = 'sitemap-spot-check';
  queueLabel = 'Pending groups';
  queueRows = (sitemap.groups || []).filter(g => !g.done).slice(0, 20)
    .map(g => ({ url: g.label || g.prefix || '?', depth: g.sample || '' }));
}

// ── Render ────────────────────────────────────────────────────────────────
const now = new Date().toISOString();
const stallCount = visitedRows.filter(r => r.status.startsWith('⚠') || r.status === '❌').length;
const successCount = visitedRows.length - stallCount;

const lines = [];
lines.push(`# Exploration State — Phase 1 Live Dashboard`);
lines.push(``);
lines.push(`> Auto-generated by \`scripts/update-exploration-state.js\` after every BFS page / trace step.`);
lines.push(`> Read this file to know what the agent is doing right now without opening any screenshots.`);
lines.push(``);
lines.push(`**Updated**: ${now}`);
lines.push(`**Strategy**: ${strategyLine}`);
lines.push(`**Fallback**: ${fallbackLine}`);
lines.push(`**Active dispatcher**: ${activeStrategy}`);
if (CURRENT_URL) lines.push(`**Current page**: ${CURRENT_URL}`);
if (NOTE)        lines.push(`**Note**: ${NOTE}`);
lines.push(``);
lines.push(`## Progress`);
lines.push(``);
lines.push(`| Metric | Value |`);
lines.push(`|---|---|`);
lines.push(`| Pages visited (snapshots on disk) | ${visitedRows.length} |`);
lines.push(`| Clean captures | ${successCount} |`);
lines.push(`| Captures with warnings | ${stallCount} |`);
lines.push(`| ${queueLabel} (showing ≤20) | ${queueRows.length}${(crawl?.queue?.length || 0) > 20 ? ` of ${crawl.queue.length}` : ''} |`);
lines.push(``);

if (queueRows.length) {
  lines.push(`## ${queueLabel}`);
  lines.push(``);
  lines.push(`| ${queueLabel === 'Queue' ? 'URL' : 'Target'} | ${queueLabel === 'Queue' ? 'Depth' : 'Step'} |`);
  lines.push(`|---|---|`);
  for (const q of queueRows) lines.push(`| ${q.url} | ${q.depth} |`);
  lines.push(``);
}

lines.push(`## Visited`);
lines.push(``);
lines.push(`| When | Status | URL | H1 | Els | Snapshot |`);
lines.push(`|---|---|---|---|---|---|`);
for (const r of visitedRows) {
  const when = r.capturedAt ? r.capturedAt.slice(11, 19) : '—';
  lines.push(`| ${when} | ${r.status} | ${r.url} | ${r.h1} | ${r.els} | \`${r.file}\` |`);
}
lines.push(``);

if (lastDecision) {
  lines.push(`## Last decision`);
  lines.push(``);
  lines.push(lastDecision);
  lines.push(``);
}

lines.push(`---`);
lines.push(``);
lines.push(`Inspect any snapshot:`);
lines.push(`\`\`\``);
lines.push(`node scripts/inspect-snapshot.js <slug>`);
lines.push(`\`\`\``);
lines.push(``);
lines.push(`Audit fidelity (run at P1→P2 transition):`);
lines.push(`\`\`\``);
lines.push(`node scripts/audit-snapshots.js`);
lines.push(`node scripts/coverage-check.js`);
lines.push(`\`\`\``);

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n') + '\n');

console.log(`✅ ${OUT} updated — ${visitedRows.length} visited, ${queueRows.length} ${queueLabel.toLowerCase()}, ${stallCount} warnings`);
